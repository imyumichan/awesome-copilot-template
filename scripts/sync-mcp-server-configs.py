#!/usr/bin/env python3
# /// script
# requires-python = ">=3.9"
# ///
"""Keep .mcp.json and .vscode/mcp.json in sync, in both directions.

The Copilot CLI plugin reads MCP server definitions from .mcp.json under a
top-level "mcpServers" key, while VS Code reads them from .vscode/mcp.json
under a top-level "servers" key. The file that differs from HEAD is the source
and the other one is regenerated by renaming only that top-level key; all
other content (key order, args order, _comment fields) is copied verbatim.

If both files differ from HEAD but are not equivalent, the script refuses to
guess and exits non-zero. Use --from to pick the source explicitly.
"""

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# side -> (path, top-level key)
FILES = {
    "base": (REPO_ROOT / ".mcp.json", "mcpServers"),
    "vscode": (REPO_ROOT / ".vscode" / "mcp.json", "servers"),
}


def other(side):
    return "vscode" if side == "base" else "base"


def rel(side):
    return FILES[side][0].relative_to(REPO_ROOT).as_posix()


def git(*args):
    return subprocess.run(
        ["git", *args], cwd=REPO_ROOT, capture_output=True, text=True, encoding="utf-8"
    )


def git_text(spec):
    """Return the content of a git object (e.g. HEAD:path, :path) or None."""
    result = git("show", spec)
    return result.stdout if result.returncode == 0 else None


def read_text(side, staged):
    """Return the file content from the index (staged) or working tree; None if absent."""
    if staged:
        return git_text(f":{rel(side)}")
    path = FILES[side][0]
    return path.read_text(encoding="utf-8") if path.exists() else None


def parse(side, text):
    """Parse and validate one config, exiting non-zero on any error."""
    key = FILES[side][1]
    other_key = FILES[other(side)][1]
    try:
        data = json.loads(text)
    except json.JSONDecodeError as exc:
        sys.exit(f"error: {rel(side)} is not valid JSON: {exc}")
    if not isinstance(data, dict) or key not in data:
        sys.exit(
            f"error: {rel(side)} must be a JSON object containing a top-level "
            f"'{key}' key"
        )
    if other_key in data:
        sys.exit(
            f"error: {rel(side)} must not contain both '{key}' and '{other_key}' keys"
        )
    return data


def convert(data, src):
    """Return a copy of data with only the top-level server key renamed.

    Top-level key order is preserved; nested content is left untouched.
    """
    src_key, dst_key = FILES[src][1], FILES[other(src)][1]
    return {(dst_key if k == src_key else k): v for k, v in data.items()}


def render(obj):
    """Serialize obj to canonical JSON text."""
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def in_sync(texts):
    if any(texts[side] is None for side in FILES):
        return False
    base, vscode = (parse(side, texts[side]) for side in ("base", "vscode"))
    return render(convert(base, "base")) == render(vscode)


def write_atomically(path, text):
    """Write text to path atomically via a temp file in the same directory."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    try:
        with tmp.open("w", encoding="utf-8") as handle:
            handle.write(text)
        os.replace(tmp, path)
    except OSError:
        if tmp.exists():
            tmp.unlink()
        raise


def main():
    parser = argparse.ArgumentParser(
        description="Sync .mcp.json (mcpServers) and .vscode/mcp.json (servers) "
        "in both directions, based on which one changed."
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check",
        action="store_true",
        help="verify both files are in sync without writing; exit non-zero if not",
    )
    mode.add_argument(
        "--from",
        dest="source",
        choices=sorted(FILES),
        help="use this file as the source instead of detecting the change via git",
    )
    parser.add_argument(
        "--staged",
        action="store_true",
        help="read the staged versions, and stage the regenerated file (pre-commit)",
    )
    args = parser.parse_args()

    texts = {side: read_text(side, args.staged) for side in FILES}

    if args.check:
        if in_sync(texts):
            return 0
        print(
            "error: .mcp.json and .vscode/mcp.json are out of sync — run "
            "scripts/sync-mcp-server-configs.py and commit both files",
            file=sys.stderr,
        )
        return 1

    src = args.source
    if src is None:
        changed = [s for s in FILES if texts[s] != git_text(f"HEAD:{rel(s)}")]
        if not changed:
            return 0
        if len(changed) == 2:
            if in_sync(texts):
                return 0
            print(
                "error: both .mcp.json and .vscode/mcp.json changed and differ; "
                "refusing to pick one. Revert/unstage one of them, or run "
                "scripts/sync-mcp-server-configs.py --from base|vscode.",
                file=sys.stderr,
            )
            return 1
        src = changed[0]

    dst = other(src)
    if texts[src] is None:
        sys.exit(f"error: source file not found: {rel(src)}")
    data = parse(src, texts[src])

    expected = render(convert(data, src))
    if texts[dst] is not None and render(parse(dst, texts[dst])) == expected:
        return 0

    if args.staged and read_text(dst, False) != texts[dst]:
        print(
            f"error: {rel(dst)} has unstaged changes that would be overwritten; "
            "stage or discard them first.",
            file=sys.stderr,
        )
        return 1

    write_atomically(FILES[dst][0], expected)
    if args.staged:
        added = git("add", "--", rel(dst))
        if added.returncode != 0:
            sys.exit(f"error: git add {rel(dst)} failed: {added.stderr.strip()}")
    print(f"wrote {rel(dst)} (from {rel(src)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
